"""## 2.2 Pares de significância
Os colchetes dos gráficos vêm do teste de Tukey (seção de estatística de cada conjunto de dados):

1. `get_plot_pairs(tukey, ...)` — pega só os pares **significativos** do Tukey e devolve um dicionário
   `{estrato: {(grupo1, grupo2): {'stars', 'p_adj', 'hide'}}}`. O estrato é `(type, Z, regiao, tempo)`,
   ou seja, cada bloco do gráfico tem os seus próprios pares.
2. `assign_symbols(pairs)` — troca as estrelas (`****`, `***`...) pelo símbolo da regra (`*`, `#`, `&`,
   ver `symbol_for`) e **esconde** os pares que não estão em nenhuma regra.
3. Ajustes manuais, se precisar:
   * `force_pair(pairs, g1, g2, '*')` — mostra um par que não está nas regras;
   * `set_hide(pairs[estrato], g1, g2)` — esconde um par específico;
   * `hide_unless(pairs, grupo)` — esconde todos os pares que não envolvem `grupo`.
4. `show_pairs(pairs)` — tabela para conferir o que vai ser desenhado (`hide=True` não é desenhado).
5. Passar `pairs=pairs` para o `plot_graph` (ou `pairs={}` para não desenhar colchete nenhum).
"""

# Colunas que identificam um estrato (um bloco do gráfico) nas tabelas de Tukey
STRATA = ['type', 'Z', 'regiao', 'tempo']


def stars(p):
    """p ajustado -> estrelas: **** p<0,0001; *** p<0,001; ** p<0,01; * p<0,05; ns."""
    return '****' if p < 1e-4 else '***' if p < 1e-3 else '**' if p < 1e-2 else '*' if p < 0.05 else 'ns'


def get_plot_pairs(tukey_df, type_=None, tempo=None, regiao=None, Z=None, hide_rule=None, nested=False):
    """
    Pares significativos (reject=True) da tabela de Tukey, no formato que o plot_graph usa.
    type_, tempo, regiao, Z : filtros opcionais da tabela (None = não filtra).
    hide_rule : função opcional (g1, g2) -> True para esconder o par desde o início.
    nested    : True -> sempre devolve {estrato: pares}; False -> se sobrar um único estrato,
                devolve só {(g1, g2): {...}}.
    """
    sub = tukey_df
    for col, val in zip(['type', 'tempo', 'regiao', 'Z'], [type_, tempo, regiao, Z]):
        if val is not None:
            sub = sub[sub[col] == val]

    if sub.empty:
        print("No Tukey rows for this filter (interaction not significant, or stratum was skipped).")
        return {}

    sub = sub[sub['reject'].astype(bool)]
    if sub.empty:
        print("Tukey rows exist, but no pair was significant.")
        return {}

    result = {}
    for _, r in sub.iterrows():
        key = tuple(r[c] for c in STRATA)
        p = float(r['p-adj'])
        result.setdefault(key, {})[(r['group1'], r['group2'])] = {
            'stars': stars(p),
            'p_adj': p,
            'hide': bool(hide_rule(r['group1'], r['group2'])) if hide_rule else False,
        }

    if len(result) == 1 and not nested:        # um estrato -> dicionário simples de pares
        return next(iter(result.values()))
    return result                              # vários estratos -> {estrato: pares}


def set_hide(pairs, g1, g2, hide=True):
    """Esconde (hide=True) ou volta a mostrar (hide=False) o par g1 x g2 de UM estrato."""
    for key in ((g1, g2), (g2, g1)):
        if key in pairs:
            pairs[key]['hide'] = hide
            return
    raise KeyError(f"Pair not found: {g1} / {g2}")


def force_pair(pairs, g1, g2, symbol='*'):
    """
    Mostra o par g1 x g2 com o símbolo `symbol`, mesmo que ele não esteja nas regras de symbol_for.
    Vale para todos os estratos em que o par foi significativo no Tukey; onde ele não foi
    significativo o par nem existe em `pairs`, então continua sem colchete (como deve ser).
    Funciona com o dicionário simples e com o aninhado. Altera no próprio lugar e devolve.
    """
    dicts = pairs.items() if is_nested(pairs) else [('(único estrato)', pairs)]
    found = []
    for strat, d in dicts:
        for key in ((g1, g2), (g2, g1)):
            if key in d:
                d[key].update(hide=False, stars=symbol)
                found.append(strat)
    print(f"force_pair {g1} x {g2}: colchete '{symbol}' em {len(found)} estrato(s)")
    for s in found:
        print('   ', s)
    if not found:
        print('    (par não significativo em nenhum estrato -> nenhum colchete)')
    return pairs


def hide_unless(pairs, group='VEI-AYA'):
    """
    Esconde (hide=True) todos os pares que NÃO envolvem `group` (um nome ou uma lista de nomes;
    o par fica visível se envolver QUALQUER um deles). Pares já escondidos continuam escondidos.
    Funciona com o dicionário simples e com o aninhado. Altera no próprio lugar e devolve.
    """
    keep = {group} if isinstance(group, str) else set(group)
    flat_dicts = list(pairs.values()) if is_nested(pairs) else [pairs]

    n_hidden = n_kept = 0
    for d in flat_dicts:
        for (a, b), v in d.items():
            if a in keep or b in keep:
                n_kept += 1
            else:
                v['hide'] = True
                n_hidden += 1
    print(f"{n_kept} pairs kept (with {sorted(keep)}), {n_hidden} hidden.")
    return pairs


def show_pairs(pairs):
    """Tabela (uma linha por par) para conferir os pares antes de desenhar."""
    rows = []
    if is_nested(pairs):
        for strat, d in pairs.items():
            for (a, b), v in d.items():
                rows.append({**dict(zip(STRATA, strat)), 'group1': a, 'group2': b, **v})
    else:
        for (a, b), v in pairs.items():
            rows.append({'group1': a, 'group2': b, **v})
    return pd.DataFrame(rows)

# Regras de símbolo dos colchetes: qual comparação recebe *, # ou &.
def _parse(name):
    """
    Separa o nome do grupo em partes:
      'VEI-AYA' -> ('drug', 'VEI', 'AYA')   (pré-tratamento - tratamento, dados 5HT2A/NAPI)
      'WT-DMT'  -> ('geno', 'WT', 'DMT')    (genótipo - droga, dados Alemanha)
    Nomes sem '-' -> None.
    """

    if '-' in name and any(s in name for s in ['WT','CXCT','NexCre']):
        gen, dr = [x.strip() for x in name.split('-', 1)]
        return ('geno', gen, dr)
    if '-' in name:
        pre, trat = [x.strip() for x in name.split('-', 1)]
        return ('drug', pre, trat)
    return None


def symbol_for(g1, g2):
    """
    Símbolo do colchete para um par de grupos, ou None se o par não está coberto pelas regras.

    Regras (dados com droga):
      *  VEI-H2O  x  VEI-AYA          (efeito da AYA sem pré-tratamento)
      #  VEI-AYA  x  <droga>-AYA      (efeito do pré-tratamento sobre a AYA)
    Regras (dados com genótipo):
      *  WT-VEI   x  WT-DMT ou <genótipo>-DMT
      #  WT-DMT   x  <genótipo>-DMT
      &  <genótipo>-VEI  x  <genótipo>-DMT   (mesmo genótipo, diferente de WT)
    Pares fora das regras podem ser mostrados com force_pair().
    """
    a, b = _parse(g1), _parse(g2)
    if a is None or b is None or a[0] != b[0]:
        return None

    if a[0] == 'drug':
        (_, p1, t1), (_, p2, t2) = a, b
        # VEI-H2O  vs  VEI-AYA
        if p1 == p2 == 'VEI' and {t1, t2} == {'H2O', 'AYA'}:
            return '*'
        # VEI-AYA  vs  <drug>-AYA
        if t1 == t2 == 'AYA' and 'VEI' in (p1, p2) and p1 != p2:
            return '#'
        return None

    (_, ge1, d1), (_, ge2, d2) = a, b
    pair = {(ge1, d1), (ge2, d2)}
    # WT-VEI  vs  WT-DMT or <genom>-DMT
    if ('WT', 'VEI') in pair and any(d == 'DMT' for _, d in pair - {('WT', 'VEI')}) and len(pair) == 2:
        return '*'
    # WT-DMT  vs  <genom>-DMT
    if ('WT', 'DMT') in pair and len(pair) == 2 and all(d == 'DMT' for _, d in pair):
        return '#'
    # <genom>-VEI  vs  <genom>-DMT   (same genotype, not WT)
    if ge1 == ge2 and ge1 != 'WT' and {d1, d2} == {'VEI', 'DMT'}:
        return '&'
    return None


def assign_symbols(pairs, unmatched='hide'):
    """
    Troca o texto 'stars' (****, ***, ...) de cada par pelo símbolo da regra (*, #, &).
    unmatched: 'hide' -> pares sem regra ficam escondidos (hide=True) (padrão)
               'keep' -> mantêm as estrelas e a visibilidade originais
    Funciona com o dicionário simples e com o aninhado {estrato: {...}}.
    Altera o dicionário no próprio lugar e também o devolve.
    """
    dicts = list(pairs.values()) if is_nested(pairs) else [pairs]
    n_ok, loose = 0, []
    for d in dicts:
        for (a, b), v in d.items():
            sym = symbol_for(a, b)
            if sym is None:
                loose.append((a, b))
                if unmatched == 'hide':
                    v['hide'] = True
            else:
                v['stars'] = sym
                n_ok += 1
    print(f"{n_ok} pairs got a symbol; {len(loose)} without a rule"
          + (" (hidden)" if loose and unmatched == 'hide' else ""))
    for a, b in sorted(set(loose)):
        print(f"   no rule: {a}  x  {b}")
    return pairs

"""## 2.3 Estatística

**Funções principais**
* `run_anova` — ANOVA entre sujeitos (pré-tratamento × tratamento, ou genótipo × droga), uma por estrato
  (ex.: cada combinação de tipo de medida, Z, região e tempo). Soma de quadrados **Tipo III** com codificação
  **Sum** (mesmo resultado do Statistica). Se a **interação entre todos os fatores** (ex.: pré-tratamento × tratamento)
  for significativa, roda Tukey entre todos os grupos.
* `run_mixed_anova` — ANOVA mista: os mesmos fatores entre sujeitos + 1 fator **intra-sujeito com 2 níveis**
  (ex.: o mesmo animal na Evocação e no Teste A). Post hoc (só se a interação tripla momento × pré-tratamento ×
  tratamento for significativa): Tukey em cada momento e teste t pareado (Holm) entre os momentos dentro de cada grupo.
* `run_rm_anova` — ANOVA de medidas repetidas com **k ≥ 2** níveis intra-sujeito (ex.: Evocação, A1, A2, A3),
  sem correção de esfericidade. Post hoc só se a interação tripla (momento × genótipo × droga) for significativa.

**O que cada função devolve** (DataFrames, prontos para salvar em Excel)
* `anova`: uma linha por termo (efeito principal ou interação) com SS, gl, F, p, η² parcial, testes de
  pressupostos (Shapiro dos resíduos, Levene), a coluna `assumptions_ok`, uma frase em português
  (`resultado`) e o texto pronto para o artigo (`F_texto`, ex.: `F(2,29) = 32,01; p < 0,001; η²p = 0,688`);
* `tukey`: uma linha por par de grupos (diferença, p ajustado, `reject` = significativo);
* `summary`: uma frase por estrato resumindo o Tukey;
* `paired` (só nas ANOVAs com medida repetida): comparações entre momentos dentro de cada grupo;
* `skipped`: estratos que **não** puderam ser analisados e o motivo (ex.: grupo com n < 2).

Todas aceitam `labels=` (fator → nome em português) para as frases da coluna `resultado`:
`LABEL_DEFAULT` (pré-tratamento / tratamento) ou `LABEL_GENO` (genótipo / droga, dados Alemanha).
"""

