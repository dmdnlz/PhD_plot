LEGEND_REPLACE = {'H2O': 'H₂O', 'NexCre': 'NEXCre'}


def legend_label(name, legend_labels=None):
    """
    Nome do grupo como aparece na legenda:
      1) troca específica do gráfico, pelo nome inteiro (legend_labels, ex.: {'VEI': 'H₂O'});
      2) depois as trocas gerais de LEGEND_REPLACE (ex.: 'VEI-H2O' -> 'VEI-H₂O').
    """
    name = (legend_labels or {}).get(name, name)
    for old, new in LEGEND_REPLACE.items():
        name = name.replace(old, new)
    return name


