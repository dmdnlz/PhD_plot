def beeswarm_offsets(values, step=0.1, bin_width=1.0, max_half_width=None,
                     max_per_group=None):
    """
    Deslocamentos horizontais dos pontos de uma barra (efeito "beeswarm"), para que pontos
    com valores parecidos não fiquem um em cima do outro.

    Os valores são agrupados de cima para baixo: pontos a menos de `bin_width` do primeiro
    ponto do grupo (e no máximo `max_per_group` pontos) ficam na mesma "linha" e são espalhados
    simetricamente em volta do centro (0, -1, +1, -2, +2... vezes `step`).
    `max_half_width` limita o espalhamento para os pontos não saírem da barra.
    """
    values = np.asarray(values, dtype=float)
    offsets = np.zeros(len(values))

    order = np.argsort(values)[::-1]

    # Greedy grouping from the highest point downward
    groups, current = [], []
    for idx in order:
        too_far = current and values[current[0]] - values[idx] > bin_width
        too_big = max_per_group and len(current) >= max_per_group
        if too_far or too_big:
            groups.append(current)
            current = []
        current.append(idx)
    if current:
        groups.append(current)

    for g in groups:
        n = len(g)

        if n % 2 == 1:
            slots = [0]
            for i in range(1, n):
                distance = (i + 1) // 2
                slots.append(-distance if i % 2 == 1 else distance)
        else:
            slots = []
            for i in range(n):
                distance = i // 2 + 0.5
                slots.append(-distance if i % 2 == 0 else distance)

        # Shrink the spacing if the outermost dot would leave the bar
        local_step = step
        max_slot = max(abs(s) for s in slots)
        if max_half_width is not None and max_slot > 0:
            local_step = min(step, max_half_width / max_slot)

        for idx, slot in zip(g, slots):
            offsets[idx] = slot * local_step

    return offsets

def get_plot_df(plot_df, regiao='CA1', drug_type='NE100', g_type='Comprimento'):
    """
    Confere os argumentos e filtra os dados do gráfico: só o g_type pedido e, exceto para
    'Comportamento', só a região pedida. Devolve também o maior valor do g_type em TODAS as
    regiões (y_max), usado para que gráficos do mesmo tipo tenham a mesma escala.
    """
    if regiao not in ['IL', 'PL', 'GD', 'CA3', 'CA1']:
        if g_type!='Comportamento':
          raise Exception(f"Região {regiao} inválida, use uma delas 'IL', 'PL', 'GD', 'CA3', 'CA1' ")
    if drug_type not in ['NE100', 'KET', '']:
        if g_type!='Densidade':
          raise Exception(f"Droga {drug_type} inválida, use uma delas 'NE100','KET' ")
    if g_type not in ['Comprimento', 'Ramificação', 'ED', 'Comportamento','Densidade']:
        raise Exception(f"Tipo {g_type} inválido, use uma delas 'Comprimento','Ramificação','ED','Comportamento','Densidade' ")

    plot_df = plot_df[plot_df["type"] == g_type]

    # Global max for this g_type (all regions/drugs), before the region filter
    y_max = pd.to_numeric(plot_df["value"], errors="coerce").max()

    if g_type!='Comportamento':
      plot_df = plot_df[plot_df["região"] == regiao]

    return plot_df, y_max

def is_nested(pairs):
    """
    True se `pairs` for o dicionário aninhado {(type, Z, regiao, tempo): {(g1, g2): {...}}}
    (um conjunto de pares por estrato); False se for o simples {(g1, g2): {...}}.
    """
    if not pairs:
        return False
    first = next(iter(pairs.values()))
    return isinstance(first, dict) and 'hide' not in first


