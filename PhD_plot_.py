def run_behavior_rm(beh):
    """RM-ANOVA (genótipo x droga x teste) para cada bloco de testes; sexos juntos."""
    beh = add_pre_trat(beh)            # pre = genótipo, trat = droga
    beh['regiao'] = 'NA'               # constante: mantém os estratos compatíveis com get_plot_pairs
    beh = beh.dropna(subset=['value'])
    # rótulos 'pre | trat' do Tukey -> nomes de 'tratamento' do gráfico (ex.: 'WT | DMT' -> 'WT-DMT')
    mapa = {f"{a} | {b}": t for a, b, t in beh[['pre', 'trat', 'tratamento']].drop_duplicates().itertuples(index=False)}

    res = {nome: run_rm_anova(beh[beh['Z'].isin(tests)], strata=['type', 'regiao'],
                              id_col='animal', within='Z', order=tests,
                              between=('pre', 'trat'), labels=LABEL_GENO)
           for nome, tests in BLOCOS.items()}

    # Junta os resultados dos blocos (coluna 'bloco' indica de qual veio)
    def cat(i):
        parts = [r[i].assign(bloco=n) for n, r in res.items() if len(r[i])]
        return pd.concat(parts, ignore_index=True) if parts else pd.DataFrame()

    anova_, tukey_, summary_, paired_, skipped_ = (cat(i) for i in range(5))
    # No Tukey, o momento (teste) vira a coluna Z, para bater com os blocos do gráfico
    tukey_ = rename_groups(tukey_, mapa).rename(columns={'momento': 'Z'})
    tukey_['tempo'] = ''
    return anova_, tukey_, rename_groups(summary_, mapa), rename_groups(paired_, mapa), skipped_


