def _check_values(df_file, col, ok, expected, where):
    """Confere se todos os valores de `col` passam no teste `ok`; imprime OK ou ERROR."""
    found = df_file[col].dropna().unique()
    if all(ok(v) for v in found):
        print(f"{where}: OK - All rows belong to {expected}")
        return True
    print(f"{where}: ERROR - expected {col} {expected}, found {found}")
    return False


def load_5ht2a_morphology(base):
    """
    Lê todas as planilhas 'dados gráfico' das subpastas de `base` e confere cada uma:
      - as colunas são as de REF_COLUMNS;
      - a região do arquivo (pelo nome: GD, CA1...) é a mesma das linhas;
      - o tempo (pelo nome da pasta: '20 min' ou não) é o mesmo das linhas;
      - a droga (pelo nome: 'sigma' -> NE100, '5ht2a' -> KET) aparece nos tratamentos.
    Arquivos com problema são avisados, mas entram nos dados (conferir as mensagens!).
    """
    frames = []
    for folder in os.listdir(base):
        folder_path = os.path.join(base, folder)
        # pula pastas de resultados, notebooks, planilhas soltas e arquivos
        if (folder == 'statistics' or '_plot' in folder or 'plot_graphs' in folder
                or '.ipynb' in folder or 'xlsx' in folder or not os.path.isdir(folder_path)):
            continue
        expected_tempo = '20 min antes evocação' if '20 min' in folder else '3h após evocação'

        for filename in os.listdir(folder_path):
            where = f'{folder}/{filename}'
            if 'Shapiro' in filename:            # planilha de teste, sem dados
                continue
            if 'sigma' in filename.lower():
                test_type = 'NE100'
            elif '5ht2a' in filename.lower():
                test_type = 'KET'
            else:
                print(f"\nCould not identify test_type in filename: {where}")
                continue
            expected_class = next((c for c in VALID_REGIONS if c in filename), None)
            if expected_class is None:
                print(f"\nCould not identify class in filename: {where}")
                continue

            try:
                df_file = pd.read_excel(os.path.join(folder_path, filename), sheet_name='dados gráfico')
            except Exception as e:
                print(f'check file: {where} -> não foi possível ler ({e})')
                continue

            if list(df_file.columns) != REF_COLUMNS:
                print(f'\n Not same_columns: check file: {where}')
            else:
                ok = [_check_values(df_file, 'região', lambda v: v == expected_class, expected_class, where),
                      _check_values(df_file, 'tempo', lambda v: v == expected_tempo, expected_tempo, where),
                      _check_values(df_file, 'tratamento', lambda v: test_type in v, test_type, where)]
                if not all(ok):
                    print(f'check file: {where}')
            frames.append(df_file)
    return pd.concat(frames, ignore_index=True)


