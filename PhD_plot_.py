# ---------- Formatação de números e frases ----------
def pretty(term):
    """Nome do termo do statsmodels -> legível: 'C(pre, Sum):C(trat, Sum)' -> 'pre × trat'."""
    return re.sub(r'C\((\w+), Sum\)', r'\1', term).replace(':', ' × ')


def fmt(x, nd=2):
    """Número com vírgula decimal."""
    return f"{x:.{nd}f}".replace('.', ',')


def fmt_p(p):
    """Valor p no formato do texto: 'p < 0,001' ou 'p = 0,023'."""
    return 'p < 0,001' if p < 0.001 else 'p = ' + fmt(p, 3)


def describe_term(row, labels=None):
    """Frase em português para um termo da ANOVA (efeito principal ou interação)."""
    label_map = labels or LABEL_DEFAULT
    names = row['termo'].split(' × ')
    labels = [label_map.get(n, n) for n in names]
    sig = row['p'] < ALPHA

    if len(names) == 1:                        # efeito principal
        lv = row['_levels'][names[0]]
        if sig:
            if len(lv) == 2:
                return f"Os dois níveis de {labels[0]} diferem ({lv[0]} vs {lv[1]})."
            return (f"Pelo menos um nível de {labels[0]} "
                    f"({', '.join(map(str, lv))}) difere dos demais.")
        return f"Sem efeito significativo de {labels[0]}."
    if sig:                                    # interação
        if len(names) == 2:
            return f"Interação: o efeito de {labels[0]} depende de {labels[1]} (e vice-versa)."
        return f"Interação entre {', '.join(labels)}: o efeito de cada fator depende dos demais."
    return f"Sem interação significativa entre {' × '.join(labels)}."


def summarize_tukey(tk):
    """Uma frase em português para uma tabela de Tukey inteira (um estrato)."""
    t = pd.DataFrame(tk._results_table.data[1:], columns=tk._results_table.data[0])
    t['reject'] = t['reject'].astype(bool)
    groups = list(tk.groupsunique)
    sig_pairs = t[t['reject']]
    if sig_pairs.empty:
        return "Nenhum par de grupos difere significativamente."

    # Quantas diferenças significativas cada grupo tem
    degree = {g: 0 for g in groups}
    for _, r in sig_pairs.iterrows():
        degree[r['group1']] += 1
        degree[r['group2']] += 1

    # Caso especial: exatamente um grupo difere de todos e nenhum outro par difere
    lone = [g for g, d in degree.items() if d == len(groups) - 1]
    if len(lone) == 1 and len(sig_pairs) == len(groups) - 1:
        return f"Somente {lone[0]} difere de todos os demais grupos."

    # Caso geral: para cada grupo, de quais ele difere
    lines = []
    for g in groups:
        if degree[g] > 0:
            others = [r['group2'] if r['group1'] == g else r['group1']
                      for _, r in sig_pairs.iterrows() if g in (r['group1'], r['group2'])]
            lines.append(f"{g} difere de: {', '.join(others)}")
    return '; '.join(lines) + '.'


# ---------- Peças comuns às três ANOVAs ----------
def tukey_table(tk, info, **extra):
    """
    Resultado do pairwise_tukeyhsd como DataFrame: uma frase por par ('resultado') e as colunas
    que identificam o estrato (info) e, se dado, o momento (extra).
    """
    t = pd.DataFrame(tk._results_table.data[1:], columns=tk._results_table.data[0])
    t['reject'] = t['reject'].astype(bool)
    padj = t['p-adj'].astype(float)
    t['resultado'] = [
        f"{g1} difere de {g2} (p-aj = {fmt(p, 4)})" if rej
        else f"Sem diferença significativa entre {g1} e {g2}"
        for g1, g2, p, rej in zip(t['group1'], t['group2'], padj, t['reject'])]
    for k, v in {**info, **extra}.items():
        t[k] = v
    return t


def check_cells(d, factors, info, skipped):
    """
    n por célula (cada combinação dos fatores, ex.: VEI-AYA). A ANOVA precisa de todas as
    combinações presentes e de pelo menos 2 animais em cada uma. Se não der, registra o motivo
    em `skipped` e devolve None.
    """
    cell_n = d.groupby(factors).size()
    expected = int(np.prod([d[f].nunique() for f in factors]))
    if len(cell_n) < expected:
        skipped.append({**info, 'motivo': f'combinações ausentes: {len(cell_n)} de {expected} células têm dados'})
        return None
    if cell_n.min() < 2:
        skipped.append({**info, 'motivo': f'uma célula tem n={cell_n.min()} (<2)'})
        return None
    return cell_n


def _f_text(r):
    # Texto pronto para colar, ex.: F(2,29) = 32,01; p < 0,001; η²p = 0,688
    return (f"F({int(r['gl'])},{int(r['gl_erro'])}) = {fmt(r['F'])}; "
            f"{fmt_p(r['p'])}; η²p = {fmt(r['eta2_parcial'], 3)}")


def build_anova_df(rows, labels=None, p_col='p', f_text=_f_text):
    """
    Monta a tabela final da ANOVA a partir das linhas: adiciona assumptions_ok (Shapiro e Levene
    com p > 0,05), a frase 'resultado' (decidida pela coluna p_col) e 'F_texto'.
    """
    anova_df = pd.DataFrame(rows)
    anova_df['assumptions_ok'] = (anova_df['p_shapiro_resid'] > 0.05) & (anova_df['p_levene'] > 0.05)
    anova_df['resultado'] = (anova_df.assign(p=anova_df[p_col])
                             .apply(lambda r: describe_term(r, labels), axis=1))
    anova_df['F_texto'] = anova_df.apply(f_text, axis=1)
    return anova_df.drop(columns='_levels')   # _levels só era usado para as frases


def add_pre_trat(df):
    """Separa o grupo nos dois fatores: 'VEI-AYA' -> pre='VEI', trat='AYA' (ou genótipo-droga: 'WT-DMT')."""
    df = df.copy()
    parts = df['tratamento'].str.split('-', n=1, expand=True)
    df['pre'] = parts[0].str.strip()
    df['trat'] = parts[1].str.strip()
    return df


def rename_groups(d, mapa, cols=('group1', 'group2', 'resultado', 'grupo')):
    """
    O Tukey nomeia os grupos como 'pre | trat' (ex.: 'WT | DMT'). Esta função troca pelos nomes de
    'tratamento' usados nos gráficos (ex.: 'WT-DMT'), para os pares baterem com as barras.
    """
    d = d.copy()
    for k, v in sorted(mapa.items(), key=lambda kv: -len(kv[0])):   # chaves mais longas primeiro
        for c in cols:
            if c in d.columns:
                d[c] = d[c].astype(str).str.replace(k, v, regex=False)
    return d


def levene_by_treatment(df, group_cols, tempo_label=None):
    """
    Teste de Levene (homogeneidade de variâncias, centrado na mediana) entre os tratamentos,
    separadamente para cada combinação de group_cols. Grupos com n < 2 são ignorados.
    """
    out = []
    for keys, g in df.groupby(group_cols):
        keys = dict(zip(group_cols, keys))
        if tempo_label is not None:
            keys['tempo'] = tempo_label

        samples = [s['value'].dropna().values for _, s in g.groupby('tratamento')]
        samples = [s for s in samples if len(s) >= 2]

        if len(samples) < 2:
            out.append({**keys, 'n_groups': len(samples), 'W': None, 'p': None})
            continue

        W, p = stats.levene(*samples, center='median')
        out.append({**keys, 'n_groups': len(samples), 'W': W, 'p': p})
    return out

def run_anova(df, strata, factors, labels=None):
    """
    ANOVA entre sujeitos, uma por estrato (Tipo III, codificação Sum).
    df      : dados com as colunas de strata, factors e 'value'.
    strata  : colunas que definem os estratos (ex.: ['type', 'Z', 'regiao', 'tempo']).
    factors : fatores da ANOVA (ex.: ['pre', 'trat']). Fatores com um só nível no estrato
              ficam de fora do modelo.
    Tukey (todos os grupos entre si) só se a interação entre TODOS os fatores do modelo for
    significativa (com pre e trat: a interação pre × trat).
    Devolve (anova, tukey, summary, skipped).
    """
    anova_rows, tukey_rows, summary_rows, skipped = [], [], [], []

    for keys, g in df.groupby(strata):
        keys = keys if isinstance(keys, tuple) else (keys,)
        info = dict(zip(strata, keys))           # ex.: {'type': 'ED', 'Z': 'Basal', ...}

        # Fatores que variam neste estrato; pre e trat são obrigatórios
        active = [f for f in factors if g[f].nunique() > 1]
        if 'pre' not in active or 'trat' not in active:
            skipped.append({**info, 'motivo': 'pre ou trat tem menos de 2 níveis'})
            continue
        cell_n = check_cells(g, active, info, skipped)
        if cell_n is None:
            continue

        # Modelo: value ~ pre * trat (efeitos principais + interação)
        formula = 'value ~ ' + ' * '.join(f'C({f}, Sum)' for f in active)
        model = smf.ols(formula, data=g).fit()
        aov = sm.stats.anova_lm(model, typ=3)
        ss_res = aov.loc['Residual', 'sum_sq']
        gl_res = aov.loc['Residual', 'df']

        # Pressupostos: normalidade dos resíduos (Shapiro) e variâncias iguais (Levene)
        p_shapiro = stats.shapiro(model.resid)[1]
        p_levene = stats.levene(*[x['value'].values for _, x in g.groupby(active)],
                                center='median')[1]
        levels = {f: sorted(g[f].unique()) for f in active}

        for term in aov.index.drop(['Intercept', 'Residual']):
            ss = aov.loc[term, 'sum_sq']
            gl = aov.loc[term, 'df']
            anova_rows.append({**info,
                               'fatores_no_modelo': ' × '.join(active),
                               'termo': pretty(term),
                               'SS': ss,
                               'gl': gl,
                               'SS_erro': ss_res,
                               'gl_erro': gl_res,
                               'MS': ss / gl,
                               'F': aov.loc[term, 'F'],
                               'p': aov.loc[term, 'PR(>F)'],
                               'eta2_parcial': ss / (ss + ss_res),
                               'n_total': len(g),
                               'n_min_cell': cell_n.min(),
                               'p_shapiro_resid': p_shapiro,
                               'p_levene': p_levene,
                               '_levels': levels})

        # Post hoc: Tukey entre todos os grupos, só se a interação entre TODOS os fatores
        # do modelo (o termo com todos eles, ex.: pre × trat) for significativa
        full = [t for t in aov.index if ':' in t and t.count(':') == len(active) - 1]
        if full and aov.loc[full[0], 'PR(>F)'] < ALPHA:
            cell = g[active].astype(str).agg(' | '.join, axis=1)    # ex.: 'VEI | AYA'
            tk = pairwise_tukeyhsd(g['value'], cell, alpha=ALPHA)
            tukey_rows.append(tukey_table(tk, info))
            summary_rows.append({**info, 'resultado': summarize_tukey(tk)})

    skipped_df = pd.DataFrame(skipped)
    if not anova_rows:
        print("Nenhum estrato pôde ser analisado. Veja skipped_df para os motivos.")
        return pd.DataFrame(), pd.DataFrame(), pd.DataFrame(), skipped_df

    tukey_df = pd.concat(tukey_rows, ignore_index=True) if tukey_rows else pd.DataFrame()
    return build_anova_df(anova_rows, labels), tukey_df, pd.DataFrame(summary_rows), skipped_df

def _within_subject_table(g, info, id_col, within, lv_w, between, skipped, what='momento'):
    """
    Validações comuns às ANOVAs com medida repetida:
      - cada animal tem no máximo uma medida por momento;
      - cada animal pertence a um único grupo.
    Devolve a tabela larga (uma linha por animal, uma coluna por momento) ou None.
    """
    if g.duplicated([id_col, within]).any():
        skipped.append({**info, 'motivo': f'mais de uma medida por animal em um mesmo {what}'})
        return None
    if g.groupby(id_col)[between].nunique().max().max() > 1:
        skipped.append({**info, 'motivo': 'um mesmo animal aparece em mais de um grupo'})
        return None
    return g.pivot(index=id_col, columns=within, values='value').reindex(columns=lv_w)


def run_mixed_anova(df, strata, id_col, within, order=None, between=('pre', 'trat'), labels=None):
    """
    ANOVA mista: 2 fatores entre sujeitos (pre, trat) x 1 fator intra-sujeito
    com 2 níveis (momento). Post hoc só se a interação momento × pre × trat for significativa.
    Com 2 níveis, é exatamente equivalente a:
      - efeitos entre sujeitos  -> ANOVA na média dos dois momentos
      - efeitos do momento e suas interações -> ANOVA na diferença (momento 2 - momento 1)
    Soma de quadrados Tipo III, codificação Sum (igual ao Statistica).

    id_col : coluna com o identificador ÚNICO de cada animal.
    within : coluna do fator intra-sujeito (ex.: 'Z' = Evocação / Teste A).
    order  : ordem dos dois níveis (o segundo é comparado com o primeiro).
    Devolve (anova, tukey, summary, paired, skipped).
    """
    between = list(between)
    anova_rows, tukey_rows, summary_rows, paired_rows, skipped = [], [], [], [], []

    for keys, g in df.groupby(strata):
        keys = keys if isinstance(keys, tuple) else (keys,)
        info = dict(zip(strata, keys))

        lv_w = list(order) if order else sorted(g[within].unique())
        g = g[g[within].isin(lv_w)]
        if len(lv_w) != 2 or g[within].nunique() != 2:
            skipped.append({**info, 'motivo': 'o fator momento não tem exatamente 2 níveis'})
            continue
        wide = _within_subject_table(g, info, id_col, within, lv_w, between, skipped)
        if wide is None:
            continue
        wide = wide.dropna()                     # só animais com os dois momentos
        if wide.empty:
            skipped.append({**info, 'motivo': 'nenhum animal com os dois momentos'})
            continue

        # Uma linha por animal: grupo + valor em cada momento + média (m) e diferença (d)
        t1, t2 = lv_w
        sub = g.drop_duplicates(id_col).set_index(id_col)[between].loc[wide.index].copy()
        sub['x1'], sub['x2'] = wide[t1], wide[t2]
        sub['m'] = (sub['x1'] + sub['x2']) / 2
        sub['d'] = sub['x2'] - sub['x1']

        cell_n = check_cells(sub, between, info, skipped)
        if cell_n is None:
            continue

        rhs = ' * '.join(f'C({f}, Sum)' for f in between)
        mb = smf.ols('m ~ ' + rhs, data=sub).fit()     # efeitos entre sujeitos
        mw = smf.ols('d ~ ' + rhs, data=sub).fit()     # momento e interações com o momento
        ab = sm.stats.anova_lm(mb, typ=3)
        aw = sm.stats.anova_lm(mw, typ=3)

        # Reescala para a SS da ANOVA mista padrão (entre x2, intra /2)
        ss_res_b, gl_res = 2 * ab.loc['Residual', 'sum_sq'], ab.loc['Residual', 'df']
        ss_res_w = aw.loc['Residual', 'sum_sq'] / 2

        # Pressupostos: o pior (menor p) entre os dois modelos
        p_shapiro = min(stats.shapiro(mb.resid)[1], stats.shapiro(mw.resid)[1])
        p_levene = min(
            stats.levene(*[x['m'].values for _, x in sub.groupby(between)], center='median')[1],
            stats.levene(*[x['d'].values for _, x in sub.groupby(between)], center='median')[1])
        levels = {f: sorted(sub[f].unique()) for f in between}
        levels['momento'] = [t1, t2]

        # Termos: (nome, SS, gl, F, p, SS do erro)
        terms = []
        for term in ab.index.drop(['Intercept', 'Residual']):
            terms.append((pretty(term), 2 * ab.loc[term, 'sum_sq'], ab.loc[term, 'df'],
                          ab.loc[term, 'F'], ab.loc[term, 'PR(>F)'], ss_res_b))
        for term in aw.index.drop('Residual'):
            # o intercepto do modelo da diferença é o efeito principal do momento
            nome = 'momento' if term == 'Intercept' else 'momento × ' + pretty(term)
            terms.append((nome, aw.loc[term, 'sum_sq'] / 2, aw.loc[term, 'df'],
                          aw.loc[term, 'F'], aw.loc[term, 'PR(>F)'], ss_res_w))

        for nome, ss, gl, F, p, ss_res in terms:
            anova_rows.append({**info,
                               'termo': nome,
                               'SS': ss, 'gl': gl,
                               'SS_erro': ss_res, 'gl_erro': gl_res,
                               'MS': ss / gl,
                               'F': F, 'p': p,
                               'eta2_parcial': ss / (ss + ss_res),
                               'n_animais': len(sub),
                               'n_min_cell': cell_n.min(),
                               'p_shapiro_resid': p_shapiro,
                               'p_levene': p_levene,
                               '_levels': levels})

        # ---------- Post hoc: só se a interação entre TODOS os fatores for significativa ----------
        # (momento × pre × trat: o termo com len(between) sinais '×')
        full_p = [p for nome, _, _, _, p, _ in terms if nome.count(' × ') == len(between)]
        if full_p and full_p[0] < ALPHA:
            cell = sub[between].astype(str).agg(' | '.join, axis=1)

            # (a) Tukey entre os grupos (pre x trat), separadamente em cada momento
            for tcol, tname in (('x1', t1), ('x2', t2)):
                tk = pairwise_tukeyhsd(sub[tcol], cell, alpha=ALPHA)
                tukey_rows.append(tukey_table(tk, info, momento=tname))
                summary_rows.append({**info, 'momento': tname, 'resultado': summarize_tukey(tk)})

            # (b) momento 2 vs momento 1 dentro de cada grupo (t pareado, correção de Holm)
            res = []
            for ck, x in sub.groupby(between):
                label = ' | '.join(map(str, ck))
                tstat, p = stats.ttest_rel(x['x2'], x['x1'])
                res.append((label, (x['x2'] - x['x1']).mean(), tstat, p))
            p_holm = multipletests([r[3] for r in res], method='holm')[1]
            for (label, diff, tstat, p), ph in zip(res, p_holm):
                if ph < ALPHA:
                    sentido = 'maior' if diff > 0 else 'menor'
                    txt = f"{label}: {t2} {sentido} que {t1} (p-aj = {fmt(ph, 4)})"
                else:
                    txt = f"{label}: sem diferença significativa entre {t1} e {t2}"
                paired_rows.append({**info, 'grupo': label,
                                    'dif_media': diff, 't': tstat, 'p': p,
                                    'p_holm': ph, 'resultado': txt})

    skipped_df = pd.DataFrame(skipped)
    if not anova_rows:
        print("Nenhum estrato pôde ser analisado. Veja skipped_df para os motivos.")
        return (pd.DataFrame(),) * 4 + (skipped_df,)

    tukey_df = pd.concat(tukey_rows, ignore_index=True) if tukey_rows else pd.DataFrame()
    return (build_anova_df(anova_rows, labels), tukey_df, pd.DataFrame(summary_rows),
            pd.DataFrame(paired_rows), skipped_df)

def _helmert(k):
    """Matriz k x (k-1) de contrastes ortonormais (Helmert), todos ortogonais ao vetor constante."""
    C = np.zeros((k, k - 1))
    for j in range(1, k):
        C[:j, j - 1] = 1.0
        C[j, j - 1] = -j
        C[:, j - 1] /= np.sqrt(j * (j + 1))
    return C


def run_rm_anova(df, strata, id_col, within, order=None, between=('pre', 'trat'),
                 sep=' | ', labels=None):
    """
    ANOVA de medidas repetidas: fatores entre sujeitos (between) x 1 fator intra-sujeito
    (within) com k >= 2 níveis. Soma de quadrados Tipo III, codificação Sum.

    Efeitos entre sujeitos -> ANOVA sobre a média dos k testes (SS reescalada por k).
    Efeitos intra-sujeito  -> ANOVA sobre k-1 contrastes ortonormais (Helmert); as SS dos
                              contrastes são somadas (= SS univariada de medidas repetidas).
    Sem correção de esfericidade: os p são os da ANOVA univariada de medidas repetidas.
    Animais sem algum dos testes são excluídos (contados em n_excluidos).
    Post hoc (só se a interação entre TODOS os fatores, momento × pre × trat, for significativa):
      (a) Tukey entre os grupos, separadamente em cada teste
      (b) t pareado entre testes dentro de cada grupo, correção de Holm (por grupo)
    Devolve (anova, tukey, summary, paired, skipped).
    """
    between = list(between)
    anova_rows, tukey_rows, summary_rows, paired_rows, skipped = [], [], [], [], []

    for keys, g in df.groupby(strata):
        keys = keys if isinstance(keys, tuple) else (keys,)
        info = dict(zip(strata, keys))

        lv_w = list(order) if order else sorted(g[within].unique())
        k = len(lv_w)
        g = g[g[within].isin(lv_w)]
        if k < 2 or g[within].nunique() != k:
            skipped.append({**info, 'motivo': f'nem todos os {k} testes têm dados'})
            continue
        wide_all = _within_subject_table(g, info, id_col, within, lv_w, between, skipped, what='teste')
        if wide_all is None:
            continue
        wide = wide_all.dropna()                 # só animais com todos os testes
        n_excl = len(wide_all) - len(wide)
        if wide.empty:
            skipped.append({**info, 'motivo': 'nenhum animal com todos os testes'})
            continue

        # Uma linha por animal: grupo + uma coluna 'y::<teste>' por teste
        sub = g.drop_duplicates(id_col).set_index(id_col)[between].loc[wide.index].copy()
        for t in lv_w:
            sub[f'y::{t}'] = wide[t]

        cell_n = check_cells(sub, between, info, skipped)
        if cell_n is None:
            continue

        Y = wide.values
        N = len(sub)
        Hm = _helmert(k)      # (não chamar de C: o patsy confundiria com o C() das fórmulas)
        sub['m'] = Y @ np.ones(k) / np.sqrt(k)  # média (escalada) dos testes de cada animal
        Z = Y @ Hm                               # k-1 contrastes entre os testes
        p_ = k - 1

        rhs = ' * '.join(f'C({f}, Sum)' for f in between)

        # ---------- efeitos entre sujeitos ----------
        mb = smf.ols('m ~ ' + rhs, data=sub).fit()
        ab = sm.stats.anova_lm(mb, typ=3)
        gl_res_b = ab.loc['Residual', 'df']
        ss_res_b = ab.loc['Residual', 'sum_sq']

        # ---------- efeitos intra-sujeito (soma sobre os k-1 contrastes) ----------
        ss_w, df_w, ss_res_w, p_shap, p_lev = {}, {}, 0.0, [], []
        for j in range(p_):
            sub['z'] = Z[:, j]
            mj = smf.ols('z ~ ' + rhs, data=sub).fit()
            aj = sm.stats.anova_lm(mj, typ=3)
            for term in aj.index.drop('Residual'):
                ss_w[term] = ss_w.get(term, 0.0) + aj.loc[term, 'sum_sq']
                df_w[term] = aj.loc[term, 'df'] * p_
            ss_res_w += aj.loc['Residual', 'sum_sq']
            p_shap.append(stats.shapiro(mj.resid)[1])
            p_lev.append(stats.levene(*[x['z'].values for _, x in sub.groupby(between)],
                                      center='median')[1])
        gl_res_w = gl_res_b * p_

        p_shapiro = min([stats.shapiro(mb.resid)[1]] + p_shap)
        p_levene = min([stats.levene(*[x['m'].values for _, x in sub.groupby(between)],
                                     center='median')[1]] + p_lev)
        levels = {f: sorted(sub[f].unique()) for f in between}
        levels['momento'] = lv_w

        # ---------- tabela de termos ----------
        terms = []   # (nome, SS, gl, SS_erro, gl_erro, intra?)
        for term in ab.index.drop(['Intercept', 'Residual']):
            terms.append((pretty(term), ab.loc[term, 'sum_sq'], ab.loc[term, 'df'],
                          ss_res_b, gl_res_b, False))
        for term in ss_w:
            nome = 'momento' if term == 'Intercept' else 'momento × ' + pretty(term)
            terms.append((nome, ss_w[term], df_w[term], ss_res_w, gl_res_w, True))

        for nome, ss, gl, sse, gle, intra in terms:
            F = (ss / gl) / (sse / gle)
            anova_rows.append({**info,
                               'termo': nome, 'intra': intra,
                               'SS': ss, 'gl': gl, 'SS_erro': sse, 'gl_erro': gle,
                               'MS': ss / gl, 'F': F, 'p': float(stats.f.sf(F, gl, gle)),
                               'eta2_parcial': ss / (ss + sse),
                               'n_animais': N, 'n_excluidos': n_excl,
                               'n_min_cell': cell_n.min(),
                               'p_shapiro_resid': p_shapiro, 'p_levene': p_levene,
                               '_levels': levels})

        # ---------- post hoc ----------
        # Só se a interação entre TODOS os fatores (momento × pre × trat) for significativa
        full_p = [r['p'] for r in anova_rows[-len(terms):] if r['termo'].count(' × ') == len(between)]
        if full_p and full_p[0] < ALPHA:
            cell = sub[between].astype(str).agg(sep.join, axis=1)

            # (a) Tukey entre os grupos em cada teste
            for t in lv_w:
                tk = pairwise_tukeyhsd(sub[f'y::{t}'], cell, alpha=ALPHA)
                tukey_rows.append(tukey_table(tk, info, momento=t))
                summary_rows.append({**info, 'momento': t, 'resultado': summarize_tukey(tk)})

            # (b) todos os pares de testes dentro de cada grupo (t pareado + Holm)
            for ck, x in sub.groupby(between):
                ck = ck if isinstance(ck, tuple) else (ck,)
                label = sep.join(map(str, ck))
                res = []
                for ta, tb in combinations(lv_w, 2):
                    tstat, pp = stats.ttest_rel(x[f'y::{tb}'], x[f'y::{ta}'])
                    res.append((ta, tb, (x[f'y::{tb}'] - x[f'y::{ta}']).mean(), tstat, pp))
                p_holm = multipletests([r[4] for r in res], method='holm')[1]
                for (ta, tb, diff, tstat, pp), ph in zip(res, p_holm):
                    if ph < ALPHA:
                        sentido = 'maior' if diff > 0 else 'menor'
                        txt = f"{label}: {tb} {sentido} que {ta} (p-aj = {fmt(ph, 4)})"
                    else:
                        txt = f"{label}: sem diferença significativa entre {ta} e {tb}"
                    paired_rows.append({**info, 'grupo': label, 'teste_1': ta, 'teste_2': tb,
                                        'dif_media': diff, 't': tstat, 'p': pp,
                                        'p_holm': ph, 'resultado': txt})

    skipped_df = pd.DataFrame(skipped)
    if not anova_rows:
        print("Nenhum estrato pôde ser analisado. Veja skipped_df para os motivos.")
        return (pd.DataFrame(),) * 4 + (skipped_df,)

    anova_df = build_anova_df(anova_rows, labels)
    tukey_df = pd.concat(tukey_rows, ignore_index=True) if tukey_rows else pd.DataFrame()
    return (anova_df, tukey_df, pd.DataFrame(summary_rows), pd.DataFrame(paired_rows), skipped_df)

